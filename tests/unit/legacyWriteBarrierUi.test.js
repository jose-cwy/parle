const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

test('HavenChat treats history_save_in_progress as a non-persisted retryable freeze', () => {
  const src = fs.readFileSync(path.join(__dirname, '../../components/haven/HavenChat.js'), 'utf8')
  assert.match(src, /history_save_in_progress/)
  assert.match(src, /\/api\/chat\/write-status/)
  assert.match(src, /setComposerRestore/)
  assert.match(src, /historySaveFrozen/)
  assert.match(src, /Your draft is still here/)
  assert.doesNotMatch(src, /NEXT_PUBLIC_PARLE_LEGACY_WRITE_BARRIER/)
})

test('HavenChat keeps the user row after a mid-stream persist fail', () => {
  const src = fs.readFileSync(path.join(__dirname, '../../components/haven/HavenChat.js'), 'utf8')
  const send = fs.readFileSync(path.join(__dirname, '../../pages/api/chat/send.js'), 'utf8')
  assert.match(send, /deferComplete:\s*true/)
  assert.match(send, /persist: 'user_only'/)
  assert.match(src, /persist === 'user_only'/)
  assert.match(src, /Your last message is saved/)
  const jsonFail = src.indexOf("data?.error === 'history_save_in_progress'")
  const userOnly = src.indexOf("streamMeta.persist === 'user_only'")
  assert.ok(jsonFail > 0 && userOnly > jsonFail)
  const restoreNearJson = src.slice(jsonFail, jsonFail + 900)
  assert.match(restoreNearJson, /setComposerRestore/)
  const restoreNearUserOnly = src.slice(userOnly, userOnly + 900)
  assert.doesNotMatch(restoreNearUserOnly, /setComposerRestore/)
})
